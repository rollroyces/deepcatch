def _load_from_json(path: Path) -> Optional[Dict]:
    """Try loading the bundled JSON from the Node.js pipeline."""
    if not path.exists():
        return None
    try:
        with open(path) as f:
            data = json.load(f)
        logger.info(f"Loaded TCGA data from {path}")
        return data
    except (json.JSONDecodeError, OSError) as e:
        logger.warning(f"Failed to load {path}: {e}")
        return None


def _build_from_literature() -> Dict[str, Any]:
    """
    Build TCGA dataset from literature-validated prevalence data.

    This is the primary data path — does NOT require API access.
    Generates simulated samples with realistic mutation patterns.

    Returns:
        dict with keys: samples, variants, metadata
    """
    rng = np.random.RandomState(SEED)
    n_healthy_per_type = 50
    n_cancer_per_type = 30

    samples = []
    variants = []

    sample_id = 0

    for cancer_type, info in LITERATURE_PREVALENCE.items():
        # Cancer samples
        for _ in range(n_cancer_per_type):
            age = int(50 + rng.randint(0, 35))
            sid = f"CANCER_{sample_id:04d}"
            samples.append({
                'sample_id': sid,
                'is_cancer': True,
                'cancer_type': cancer_type,
                'age': age,
                'tmb': float(TMB_MEDIAN.get(cancer_type, 3.0)),
            })

            # Assign mutations per gene prevalence
            n_mutations = int(np.clip(TMB_MEDIAN.get(cancer_type, 3.0) * rng.uniform(0.3, 2.0), 1, 50))
            for m in range(n_mutations):
                # Select gene proportional to prevalence
                gene_idx = rng.choice(len(info['genes']),
                                      p=np.array([g['prevalence'] for g in info['genes']]) /
                                      sum(g['prevalence'] for g in info['genes']))
                gene = info['genes'][gene_idx]
                if rng.random() < gene['prevalence']:
                    tissue_vaf = rng.uniform(0.05, 0.50)  # heterozygous mutation VAF
                    variants.append({
                        'sample_id': sid,
                        'cancer_type': cancer_type,
                        'gene': gene['gene'],
                        'chrom': f"chr{1 + (sample_id + m) % 22}",
                        'pos': 1000000 + sample_id * 500 + m * 100,
                        'tissue_vaf': float(tissue_vaf),
                        'expected_ctdna_vaf': float(tissue_vaf * 0.001),
                    })

            sample_id += 1

        # Healthy controls
        for _ in range(n_healthy_per_type):
            sid = f"HEALTHY_{sample_id:04d}"
            age = int(45 + rng.randint(0, 40))
            samples.append({
                'sample_id': sid,
                'is_cancer': False,
                'cancer_type': cancer_type,
                'age': age,
                'tmb': 0.0,
            })
            sample_id += 1

    return {
        'dataset': {
            'samples': samples,
            'variants': variants,
        },
        'chip_data': {
            'genes': CHIP_GENES,
            'reference': 'Genovese 2014 NEJM; Jaiswal 2014 NEJM',
        },
        'trinuc_error_rates': {
            'C_G': 12.0, 'T_C': 4.0, 'A_T': 5.5, 'G_A': 3.5,
            'C_T': 2.8, 'A_G': 2.0, 'T_A': 1.8, 'G_T': 1.5, 'default': 1.0,
            'reference': 'Newman 2016 Nat Biotech; Phallen 2017 Sci Transl Med',
        },
        'shedding_rates': SHEDDING_RATES,
        'growth_params': GOMPERTZ_PARAMS,
        'cosmic_prevalence': LITERATURE_PREVALENCE,
        'tmb_median': TMB_MEDIAN,
        'metadata': {
            'data_source': 'COSMIC v99 + TCGA PanCancer Atlas (hardcoded with citations)',
            'generated': True,
            'fallback': 'API not called — using literature prevalence',
        },
    }


def load_tcga_data(force_fallback: bool = False) -> Dict[str, Any]:
    """
    Load TCGA/COSMIC mutation data.

    Strategy:
      1. Try bundled JSON from Node.js pipeline
      2. Fall back to literature-validated hardcoded frequencies

    Args:
        force_fallback: If True, skip JSON and go straight to fallback.

    Returns:
        dict with keys: dataset (samples, variants), chip_data,
                        trinuc_error_rates, shedding_rates, metadata
    """
    if not force_fallback:
        # Try the Node.js generated dataset first
        data = _load_from_json(TCGA_INPUT_PATH)
        if data is not None:
            return data

    logger.info("Building TCGA dataset from literature prevalence (no JSON available)")
    return _build_from_literature()


def get_shedding_rate(cancer_type: str) -> Dict[str, float]:
    """Get cfDNA shedding parameters for a cancer type."""
    return SHEDDING_RATES.get(cancer_type, SHEDDING_RATES.get('LUAD', {}))


def get_chip_genes() -> List[Dict]:
    """Get CHIP gene definitions."""
    return CHIP_GENES


def chip_prevalence(age: int) -> float:
    """
    CHIP prevalence: age-dependent logistic curve.

    Prevalence: ~2% at 50 → ~25% at 80
    Source: Genovese 2014 NEJM; Jaiswal 2014 NEJM
    """
    if age < 40:
        return 0.0
    return min(0.30, 0.25 / (1.0 + np.exp(-(age - 70) / 8.0)))


def get_gompertz_params(cancer_type: str) -> Dict[str, float]:
    """Get Gompertz growth parameters for a cancer type."""
    return GOMPERTZ_PARAMS.get(cancer_type, GOMPERTZ_PARAMS['LUAD'])


