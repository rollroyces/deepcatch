"""The API contract the user guide describes must be the API's contract.

Why this file exists
--------------------
`docs/USER_GUIDE.md` tells a reader what the REST API returns: a table of
response fields (`classical.mds_simpson`, `neural.probability`,
`explanation.top_motifs`, ...) and the method names the endpoint accepts
(`classical`, `neural`, `ensemble`). A reader who follows the guide
against a renamed field gets a response that no longer matches the
documentation, and a reviewer who compares the two sees the
documentation drift from the code.

The guide is generated by hand and the schema by hand as well, so
nothing connected them: renaming a field in `api/schemas.py` changes the
API without changing the sentence in the guide that describes it.

What this test checks, and what it deliberately does not
-------------------------------------------------------
Every response field the guide's table names must exist in the API's
schema, and every method the guide mentions must be one the endpoint
accepts. The field list is read from the guide itself rather than
duplicated here, so the check follows the document instead of a second
copy of it.

It does not call the API. The schema is the contract; a live call would
test the server, which the API's own test module does.
"""
from __future__ import annotations

import re
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent
_GUIDE = _REPO_ROOT / "docs" / "USER_GUIDE.md"
_SCHEMA = _REPO_ROOT / "api" / "schemas.py"

# The table of response fields, as markdown rows of `| `field` | meaning |`.
_FIELD_ROW = re.compile(r"^\|\s*`([a-z_]+\.[a-z_]+)`\s*\|", re.M)

# A method the endpoint accepts.
_METHOD = re.compile(r'"method":\s*"([a-z]+)"')

# A pydantic field declaration: a name, a type and a colon, indented one
# level inside a class. Looking for the *declaration* rather than the
# name anywhere in the file matters: the schema's docstrings carry JSON
# examples that mention the same field names, so a search over the whole
# file would pass even after the field had been renamed.
_FIELD_DEF = re.compile(r"^\s{4}([a-z_][a-z0-9_]*)\s*:\s", re.M)


def _guide_fields() -> list[str]:
    """The dotted response fields the guide's table names."""
    return _FIELD_ROW.findall(_GUIDE.read_text(encoding="utf-8"))


def _guide_methods() -> list[str]:
    """The method names the guide shows in a request."""
    return sorted(set(_METHOD.findall(_GUIDE.read_text(encoding="utf-8"))))


def test_the_guide_s_response_fields_exist_in_the_schema():
    """Every field the guide names must be a field of the API's schema."""
    schema = _SCHEMA.read_text(encoding="utf-8")
    declared = set(_FIELD_DEF.findall(schema))
    fields = _guide_fields()
    assert fields, (
        "the guide's response table was not found -- the check would be "
        "vacuous"
    )

    missing = []
    for dotted in fields:
        for part in dotted.split("."):
            if part not in declared:
                missing.append(f"{dotted} (no '{part}' field in api/schemas.py)")

    assert not missing, (
        "the guide documents response fields the API does not have:\n  "
        + "\n  ".join(missing)
        + "\nEither the field is documented wrongly or the API changed; a "
          "reader who follows the guide gets a different response."
    )


def test_the_methods_the_guide_shows_are_accepted_by_the_endpoint():
    """The method names in the guide's examples must be real methods."""
    schema = _SCHEMA.read_text(encoding="utf-8")
    methods = _guide_methods()
    assert methods, "no method found in the guide's examples"

    missing = [
        method for method in methods
        if not re.search(rf'^\s+{re.escape(method.upper())}\s*=\s*"{method}"',
                         schema, re.M)
    ]
    assert not missing, (
        "the guide shows methods the endpoint does not accept: "
        + ", ".join(missing)
        + "\nThe accepted values are the members of PredictionMethod in "
          "api/schemas.py."
    )


def test_the_guide_names_the_response_fields_it_claims_to():
    """A sanity check on the extractor: it must find the known fields."""
    fields = _guide_fields()
    assert "classical.mds_simpson" in fields
    assert "neural.probability" in fields
    assert "explanation.top_motifs" in fields
